"""Continuum corpus: synthetic English lives and their criteria, fixed before any run.

Criteria are judge instructions. They never reach a host: the runner sends only
the user messages of each life. Docs: docs/50_continuum_benchmark.md.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Life:
    id: str
    family: str
    counter: bool
    telling: tuple[str, ...]
    change: tuple[str, ...]
    asking: str
    must_use: tuple[str, ...]      # earlier facts the reply relies on ("Remembers")
    must_not: tuple[str, ...]      # outdated or unrelated context the reply must not apply
    no_repeat: tuple[str, ...]     # what the reply must not ask again
    unknown: tuple[str, ...]       # never given: stating it as known is inventing
    next_step: str                 # what counts as a useful next step here
    elsewhere: int                 # index into ELSEWHERE


